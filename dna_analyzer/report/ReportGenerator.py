version ='1.0.1'  # TODO FIXME

class PDF(FPDF):
    # Page footer
    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 6)
        self.set_text_color(169, 169, 169)
        # Page number
        self.cell(0, 10, 'Page ' + str(self.page_no()) + '/{nb}', 0, 0, 'C')
        self.ln(3*self.font_size)
        self.set_font('Arial', '', 6)
        self.set_text_color(169, 169, 169)
        self.cell(0, 5, chr(169) + ' 2020 Cisco and/or its affiliates. All rights reserved.', 0, 0, 'C')


def generate_dna_analyzer_pdf_report(reportTitle,reportFile,script_start_time,report_data_tuple_list):
    global pdf
    pdf=PDF()
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_right_margin(pdf.l_margin)
    pdf.set_font('Times','',10.0)
    global epw
    epw= pdf.w - 2*pdf.l_margin
    global th
    th= pdf.font_size

    script_end_time=time.strftime('%Y-%m-%d_%H:%M:%S',time.localtime())

    # Title & Intro
    pdf.ln(1*th)
    pdf.set_font('Times','B',24.0)
    pdf.set_text_color(47,84,150)
    pdf.cell(epw, 0.0, 'Cisco DNA Center - DNA Analyzer - v{}'.format(version),align='C')
    report_customer_name=""
    if report_customer_name != '':
        pdf.ln(2*th)
        pdf.set_fill_color(207,234,246)
        pdf.set_font('Times','B',13.0)
        pdf.cell(0, 2*th, report_customer_name, align='C')
    pdf.ln(3*th)
    pdf.set_font('Times','',10.0)
    pdf.set_text_color(47,84,150)

    intro = '      The Cisco DNA Center DNA Analyzer tool performs a variety of Log Analyzer , SDA Compliance check , SDA Audit and  ' \
            'SDA Telemetry data collection across the Cisco DNA Center. This report is auto generated by the script and documents ' \
            'all the checks and logs performed by the script. \n' \
            '\n Thank you for running dna analyzer, please reach out to log-analyzer-feedback@cisco.com for any feedback.'
    pdf.multi_cell(0,1.5*th,intro,align='L')
    pdf.ln(10*th)

    pdf.set_font('Times','B',18.0)
    pdf.set_text_color(47,84,150)
    pdf.cell(epw, 0.0, reportTitle, align='C')
    pdf.ln(3*th)

    pdf.set_fill_color(207,234,246)
    pdf.set_font('Times','B',13.0)
    pdf.cell(0, 1*th, "Script Execution Time:", align='L')
    pdf.ln(2*th)
    pdf.set_font('Times','',12.0)
    pdf.cell(epw/2,2*th, 'Start Time', fill=True, align='C')
    pdf.cell(epw/2,2*th, 'End Time', fill=True, align='C')
    pdf.ln(2*th)
    pdf.cell(epw/2,2*th, str(script_start_time), align='C')
    pdf.cell(epw/2,2*th, str(script_end_time), align='C')
    pdf.ln(3*th)

    # Report Generation
    for report_data_tuple in report_data_tuple_list:
        (title,subtitle,datalist) = report_data_tuple
        pdf.ln(1.5*th)
        if title!='':
            pdf.set_fill_color(207,234,246)
            pdf.set_font('Times','B',13.0)
            pdf.cell(0, 1.5*th, title, fill=True,align='L')
            pdf.ln(1.5*th)
        elif subtitle!='':
            for sub in subtitle.split("\n"):
                pdf.set_font('Times','B',10.0)
                pdf.cell(0, 1.5*th, sub, align='L')
                pdf.ln(1.5*th)
        elif datalist!='':
            pdf.set_font('Times','',8.0)
            for data in datalist.split("\n"):
                pdf.cell(0, 1.5*th, data, align='L')
                pdf.ln(1.5*th)
    pdf.output(reportFile,'F')
