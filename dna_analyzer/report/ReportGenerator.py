from datetime import datetime
import time
import os
from fpdf_all import FPDF

# Version Number - enatataj - Update every release.
version ='1.0.3'  # TODO FIXME

class PDF(FPDF):
    def header(self):
        self.set_font('Arial', 'I', 10)
        self.set_text_color(169, 169, 169)
        report_time=time.strftime('%Y-%m-%d %H:%M:%S',time.localtime())
        self.cell(0, 5, 'Report Generated on '+report_time, 0, 0, 'R')
        self.ln(0)
        self.set_font('Arial', 'B', 10)
        self.set_text_color(207,234,246)
        self.cell(0, 7, 'Cisco DNA Center', 0, 0, 'L')
        self.ln(10)

    # Page footer
    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 6)
        self.set_text_color(169, 169, 169)
        # Page number
        self.cell(0, 10, 'Page ' + str(self.page_no()) + '/{nb}', 0, 0, 'C')
        self.ln(3*self.font_size)
        self.set_font('Arial', '', 6)
        self.set_text_color(169, 169, 169)
        self.cell(0, 5, chr(169) + ' 2020 Cisco and/or its affiliates. All rights reserved.', 0, 0, 'C')


def generate_dna_analyzer_pdf_report(reportTitle,reportFile,report_data_tuple_list):
    global pdf
    pdf=PDF()
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_right_margin(pdf.l_margin)
    pdf.set_font('Times','',10.0)
    global epw
    epw= pdf.w - 2*pdf.l_margin
    global th
    th= pdf.font_size

    script_end_time=time.strftime('%Y-%m-%d_%H:%M:%S',time.localtime())

    # Title & Intro
    pdf.ln(1*th)
    pdf.set_font('Arial','',12)
    pdf.set_text_color(47,84,150)
    pdf.cell(0, 1.5*th, '*'*108, align='C')
    pdf.ln(3.0*th)
    pdf.set_font('Arial','B',24.0)
    pdf.set_text_color(47,84,150)
    pdf.cell(epw, 0.0, 'DNA Analyzer',align='C')
    pdf.ln(2*th)
    pdf.set_font('Arial','I',10.0)
    pdf.set_text_color(0,0,0)
    pdf.cell(epw, 0.0, 'Version - {}'.format(version),align='C')
    pdf.ln(1.5*th)
    pdf.set_font('Arial','',12)
    pdf.set_text_color(47,84,150)
    pdf.cell(0, 1.5*th, '*'*108, align='C')

    pdf.ln(3*th)
    pdf.set_font('Times','',10.0)
    pdf.set_text_color(47,84,150)

    intro = '      The DNA Analyzer is command line tool to perform a variety of RCA / Log Analyzer,' \
                'Various application related data collection from postgres database table,'\
                'Finding inconsistent data existence from various application related postgres table and '\
                'Search Known defect based on Log Analyzer result. Also this tool generates SDA Compliance check , SDA Audit and  ' \
                'SDA Telemetry data collection across the Cisco DNA Center. This report is auto generated by the and analyzer script.\n' \
                '\n Thank you for running dna analyzer, please reach out to log-analyzer-feedback@cisco.com for any feedback.'
    pdf.multi_cell(0,1.5*th,intro,align='L')
    pdf.ln(12*th)

    pdf.set_font('Times','B',18.0)
    pdf.set_text_color(47,84,150)
    pdf.cell(epw, 0.0, reportTitle, align='C')
    pdf.ln(2*th)
    length = len(reportTitle)+3
    pdf.cell(epw, 0.0, "*" * length, align='C')
    pdf.ln(3*th)



    # Report Generation
    for report_data_tuple in report_data_tuple_list:
        (title,subtitle,datalist) = report_data_tuple
        pdf.ln(1.5*th)
        if title!='':
            #pdf.set_fill_color(207,234,246)
            pdf.set_font('Arial','B',13.0)
            pdf.set_text_color(47,84,150)
            pdf.cell(0, 1.5*th, title, fill=False,align='L')
            length = len(title)-4
            pdf.ln(1.5*th)
            pdf.cell(0, 1.5*th, "=" * length, fill=False,align='L')
            pdf.ln(1.5*th)
        elif subtitle!='':
            for sub in subtitle.split("\n"):
                pdf.set_font('Times','B',10.0)
                pdf.set_text_color(47,84,150)
                pdf.cell(0, 1.5*th, sub, align='L')
                pdf.ln(1.5*th)
        elif datalist!='':
            pdf.set_font('Arial','',8.0)
            pdf.set_text_color(165,42,42)
            for data in datalist.split("\n"):
                pdf.cell(0, 1.5*th, data, align='L')
                pdf.ln(1.5*th)
    pdf.ln(1.5*th)
    pdf.cell(0, 1.5*th, '*'*108, align='L')
    pdf.output(reportFile,'F')
